export type Language = keyof typeof TRANSLATIONS;

export interface LanguageContextType {
  lang: Language;
  changeLanguage: (newLang: Language) => void;
  t: (key: string) => string;
}

export const LanguageContext = createContext<LanguageContextType | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Language>(() => {
    const saved = localStorage.getItem('majorrss_lang');
    if (saved && saved in TRANSLATIONS) {
      return saved as Language;
    }
    if (typeof navigator !== 'undefined') {
      const systemLang = navigator.language.toLowerCase();
      if (systemLang.startsWith('zh')) return 'zh';
      if (systemLang.startsWith('ko')) return 'ko';
      if (systemLang.startsWith('ja')) return 'ja';
      if (systemLang.startsWith('ru')) return 'ru';
    }
    return 'zh';
  });

  const changeLanguage = (newLang: Language) => {
    setLang(newLang);
    localStorage.setItem('majorrss_lang', newLang);
  };

  const t = (key: string): string => {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
    // @ts-ignore
    return dict[key] || TRANSLATIONS['en'][key] || key;
  };

  return React.createElement(LanguageContext.Provider, { value: { lang, changeLanguage, t } }, children);
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
